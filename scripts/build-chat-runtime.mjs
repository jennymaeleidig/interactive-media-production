// Build the chat's shipped runtime (`scripts/chat-runtime.js`).
//
// Two generated, committed files come out of here, and both are generated for
// the same reason: the browser cannot compile Yarn and cannot resolve a module
// graph, so neither step can happen on the page.
//
//   1. `scripts/chat-program.json` — `dialogue/flock.yarn` compiled once, at
//      build time, with the Node loader (`yarnspinner-typescript/node`). Keys
//      are sorted recursively so the bytes are a function of the source alone.
//   2. `scripts/chat-runtime.js` — `scripts/chat-engine.mjs` bundled by
//      esbuild into one IIFE (the program inlined, the block inventory inlined,
//      the dialogue runtime's browser build tree-shaken). One file is what
//      `/chat/runtime.js` publishes, so the engine and the program it reads can
//      never ship out of step. The React shell ships in the page's own Next
//      bundle and reaches the engine only through its declared interface.
//
// Both are in memory here, so one command can write them and another can ask
// whether the committed bytes still follow from the sources:
//
//   npm run chat:build    write them
//   npm run chat:check    fail if the committed bytes are stale (CI, pre-build)
//
// SPDX-License-Identifier: CC0-1.0
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { loadYarnProject } from 'yarnspinner-typescript/node';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PROJECT_FILE = path.join(ROOT, 'assets/dialogue', 'flock.yarnproject');
const PROGRAM_FILE = path.join(ROOT, 'scripts', 'chat-program.json');
const ENGINE_FILE = path.join(ROOT, 'scripts', 'chat-engine.mjs');
const RUNTIME_FILE = path.join(ROOT, 'scripts', 'chat-runtime.js');

const HEADER = [
  '// generated by scripts/build-chat-runtime.mjs — edit the sources',
  '// sources: scripts/chat-engine.mjs + lib/chat-blocks.mjs + scripts/chat-program.json',
  '',
  '',
].join('\n');

/**
 * Sort every object's keys recursively so the compiled program's bytes depend
 * on the source, not on the compiler's insertion order. Array order is
 * semantic (instructions, lines) and is preserved.
 * @param {unknown} value
 * @returns {unknown}
 */
function stableKeys(value) {
  if (Array.isArray(value)) return value.map(stableKeys);
  if (value && typeof value === 'object') {
    /** @type {Record<string, unknown>} */
    const sorted = {};
    for (const key of Object.keys(value).sort()) {
      sorted[key] = stableKeys(/** @type {Record<string, unknown>} */ (value)[key]);
    }
    return sorted;
  }
  return value;
}

/**
 * Compile `dialogue/flock.yarn` into the deterministic program JSON, including
 * its trailing newline.
 * @returns {string}
 */
function compileProgram() {
  const project = loadYarnProject(PROJECT_FILE);
  if (!project.program) {
    const problems = project.diagnostics.map((diagnostic) => `${diagnostic.code}: ${diagnostic.message}`).join('\n');
    throw new Error(`assets/dialogue/flock.yarn failed to compile:\n${problems}`);
  }
  return `${JSON.stringify(stableKeys(project.program), null, 2)}\n`;
}

/** Bundle the engine, inlining the freshly compiled program. @param {string} program @returns {Promise<string>} */
async function bundleRuntime(program) {
  const result = await build({
    entryPoints: [ENGINE_FILE],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2017',
    legalComments: 'none',
    write: false,
    // The engine imports `./chat-program.json`; resolve that to the bytes just
    // compiled, not the copy on disk. Reading the disk here would inline the
    // previous compile and ship a runtime one edit behind its program.
    plugins: [
      {
        name: 'fresh-program',
        setup(pluginBuild) {
          pluginBuild.onLoad({ filter: /chat-program\.json$/ }, () => ({ contents: program, loader: 'json' }));
        },
      },
    ],
  });
  return HEADER + result.outputFiles[0].text;
}

/**
 * The bytes both generated files should carry, without touching the disk.
 * @returns {Promise<{ program: string, runtime: string }>}
 */
export async function buildChatRuntime() {
  const program = compileProgram();
  return { program, runtime: await bundleRuntime(program) };
}

/** The committed bytes, or null when the file is absent. @param {string} file */
function committed(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

async function main() {
  const { program, runtime } = await buildChatRuntime();
  if (process.argv.includes('--check')) {
    /** The generated files, and the bytes they must match. */
    const generated = [
      ['scripts/chat-program.json', PROGRAM_FILE, program],
      ['scripts/chat-runtime.js', RUNTIME_FILE, runtime],
    ];
    const stale = generated.filter(([, file, bytes]) => committed(file) !== bytes).map(([name]) => name);
    if (stale.length > 0) {
      console.error(`stale: ${stale.join(', ')} no longer follow from the chat sources`);
      console.error('run `npm run chat:build` and commit the result');
      process.exit(1);
    }
    console.log(`chat sources and committed bytes agree (${program.length} + ${runtime.length} bytes)`);
    return;
  }
  writeFileSync(PROGRAM_FILE, program, 'utf8');
  writeFileSync(RUNTIME_FILE, runtime, 'utf8');
  console.log(`chat-program.json: ${program.length} bytes`);
  console.log(`chat-runtime.js:   ${runtime.length} bytes`);
}

// Only when run as a command: the freshness gate's own test imports the builder.
if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
