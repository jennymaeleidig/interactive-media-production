// Turn the committed `served/` tree into the static artifact a host can serve:
// the tree verbatim, a route-path copy of every non-root page, one client-side
// redirect page per local `served/redirects.json` entry, and one `404.html` carrying
// the serving layer's own not-found body.
//
// Why the copies exist: a static host serves `/<route>` from `/<route>.html` by
// an appending rule we do not control, and falls back to a directory redirect
// (`/<route>` → `/<route>/` → `index.html`) when the rule does not fire. Shipping
// both makes correctness independent of the rule; only the 200-versus-301 hop
// depends on it (spec decision 3/4).
//
// The mapping, generated bytes and budget math are pure (`planArtifact`,
// `redirectPageBytes`, `artifactBytes`, `budgetFailures`) so they can be tested
// without a filesystem; `materialize` is the thin edge that reads the tree,
// refuses collisions and an over-budget artifact *before writing anything*, and
// otherwise writes the planned entries. The materialization only ever reads
// `served/` — the tree is the artifact, never an input to be edited.
//
// SPDX-License-Identifier: CC0-1.0
import { copyFile, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { invokedDirectly, makeArg } from './cli.mjs';
import { NOT_FOUND_BODY } from './not-found.mjs';
import { isLocalTarget } from './run-manifest.mjs';
import { insideTree, routeIndexFile, routeOfPage } from './served-tree.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');

/** The published-site ceiling GitHub Pages documents (1 GB). */
export const ARTIFACT_BYTE_CAP = 1_000_000_000;

/**
 * One file the artifact must carry: a verbatim copy of a served file (`copy`),
 * or generated bytes (`body`). `origin` names where it came from, so a collision
 * can say which two producers wanted the same path.
 * @typedef {{ path: string, origin: string } & ({ copy: string } | { body: string })} ArtifactEntry
 */

/**
 * A redirect source's route, normalized so `//foo` and `/foo/` name the same
 * page — the manifest is data, and a trailing slash must not mint a second path.
 * @param {string} source
 * @returns {string}
 */
function normalizeRoute(source) {
  return '/' + source.replace(/^\/+/, '').replace(/\/+$/, '');
}

/**
 * Escape a string for use in an HTML attribute or text node. Redirect targets
 * come from a committed build artifact, but escaping keeps a target that reads
 * as markup from breaking the page it is injected into.
 * @param {string} value
 * @returns {string}
 */
function escapeHtml(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * The generated client-side redirect page for a manifest source: a canonical
 * link at the target, a `meta` refresh, a JS `location.href` fallback, a
 * `noindex` directive and a visible fallback link. The five parts carry the
 * redirect for a browser, a crawler and a no-JS reader alike.
 * @param {string} target  a root-relative local target, as `planArtifact` admits it
 * @returns {string}
 */
export function redirectPageBytes(target) {
  const attr = escapeHtml(target);
  // JSON.stringify quotes and escapes the string for JS; `<` is escaped so a
  // target can never close the script element it sits inside.
  const script = JSON.stringify(target).replace(/</g, '\\u003c').replace(/>/g, '\\u003e');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Redirecting</title>
<link rel="canonical" href="${attr}">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=${attr}">
</head>
<body>
<p>This page moved to <a href="${attr}">${attr}</a>.</p>
<script>location.href = ${script};</script>
</body>
</html>
`;
}

/**
 * The artifact paths produced by more than one entry, as named failures. Pure:
 * it is the collision rule the run refuses on, independent of the filesystem.
 * @param {ArtifactEntry[]} entries
 * @returns {string[]}
 */
function collisions(entries) {
  /** @type {Map<string, string[]>} */
  const origins = new Map();
  for (const entry of entries) {
    const list = origins.get(entry.path);
    if (list) list.push(entry.origin);
    else origins.set(entry.path, [entry.origin]);
  }
  const failures = [];
  for (const [file, claimants] of origins) {
    if (claimants.length > 1) {
      failures.push(`artifact path '${file}' is produced more than once: ${claimants.join(' and ')}`);
    }
  }
  return failures;
}

/**
 * The complete artifact plan for a served-tree file listing and a redirect
 * manifest: every entry that must be written and the collisions that forbid the
 * run. Pure — no filesystem, no reader — so the mapping and generated bytes are
 * testable in isolation (spec testing decisions).
 * @param {{ files: string[], redirects: Record<string, string> }} input
 * @returns {{ entries: ArtifactEntry[], failures: string[] }}
 */
export function planArtifact({ files, redirects }) {
  /** @type {ArtifactEntry[]} */
  const entries = [];
  // the tree verbatim
  for (const file of files) {
    entries.push({ path: file, origin: `served/${file}`, copy: file });
  }
  // a route-path copy of every non-root page, so `/<route>` resolves even if the
  // host's `.html`-appending rule does not fire
  for (const file of files) {
    const route = routeOfPage(file);
    if (route === null || route === '/') continue;
    const to = routeIndexFile(route);
    if (to === file) continue; // already living at its route index
    entries.push({ path: to, origin: `route copy of served/${file}`, copy: file });
  }
  // one client-side redirect page per local manifest entry. The serving layer
  // 404s a non-local target (`isLocalTarget`), so the artifact must too — a page
  // that redirected a `//host` target off-machine would answer differently from
  // the Recreation and break its zero-outbound invariant.
  for (const [source, target] of Object.entries(redirects)) {
    if (!isLocalTarget(target)) continue;
    entries.push({
      path: routeIndexFile(normalizeRoute(source)),
      origin: `redirect '${source}'`,
      body: redirectPageBytes(target),
    });
  }
  // the single not-found page, carrying the serving layer's own body
  entries.push({ path: '404.html', origin: 'not-found body', body: NOT_FOUND_BODY });
  return { entries, failures: collisions(entries) };
}

/**
 * The artifact's byte size: copied files measured by the caller's reader,
 * generated bytes by their UTF-8 length. Pure.
 * @param {ArtifactEntry[]} entries
 * @param {(from: string) => number} sizeOf
 * @returns {number}
 */
export function artifactBytes(entries, sizeOf) {
  let total = 0;
  for (const entry of entries) {
    total += 'copy' in entry ? sizeOf(entry.copy) : Buffer.byteLength(entry.body, 'utf8');
  }
  return total;
}

/**
 * Whether an artifact of `bytes` fits the published-site cap. Pure.
 * @param {number} bytes
 * @param {number} [cap]
 * @returns {string[]}
 */
export function budgetFailures(bytes, cap = ARTIFACT_BYTE_CAP) {
  if (bytes <= cap) return [];
  return [`artifact is ${bytes} bytes, ${bytes - cap} over the ${cap}-byte published-site cap`];
}

/**
 * Every file under `dir`, as relative POSIX paths, sorted for a deterministic
 * plan. The materializer reads the same listing it will copy, so what it plans
 * and what it writes cannot disagree.
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
export async function listFiles(dir) {
  /** @type {string[]} */
  const out = [];
  /** @param {string} current @param {string} prefix */
  async function walk(current, prefix) {
    const items = await readdir(current, { withFileTypes: true });
    items.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const item of items) {
      const rel = prefix === '' ? item.name : `${prefix}/${item.name}`;
      if (item.isDirectory()) await walk(path.join(current, item.name), rel);
      else out.push(rel);
    }
  }
  await walk(dir, '');
  return out;
}

/** A refused materialization, carrying the named failures that refused it. */
export class ArtifactRefusedError extends Error {
  /** @param {string[]} failures */
  constructor(failures) {
    super(`publish artifact refused:\n  ${failures.join('\n  ')}`);
    this.name = 'ArtifactRefusedError';
    /** @type {string[]} */
    this.failures = failures;
  }
}

/**
 * The build's redirect table, or an empty one when the run wrote no stubs —
 * `lib/serving.ts` documents an absent table as legitimate, so the artifact
 * must not be the one reader that throws. A table that exists but does not
 * parse is a corrupt build artifact and still fails loudly.
 * @param {string} servedDir
 * @returns {Promise<Record<string, string>>}
 */
async function readRedirects(servedDir) {
  try {
    return JSON.parse(await readFile(path.join(servedDir, 'redirects.json'), 'utf8'));
  } catch (err) {
    if (err && typeof err === 'object' && 'code' in err && err.code === 'ENOENT') return {};
    throw err;
  }
}

/**
 * Materialize `servedDir` into `outDir`. The plan is validated — collisions and
 * budget — before anything is written, so a refused run leaves no output behind;
 * on success the output is rebuilt from scratch. `servedDir` is only read.
 * @param {{ servedDir: string, outDir: string, cap?: number }} input
 * @returns {Promise<{ files: number, bytes: number }>}
 */
export async function materialize({ servedDir, outDir, cap = ARTIFACT_BYTE_CAP }) {
  const served = path.resolve(servedDir);
  const out = path.resolve(outDir);
  if (out === served || insideTree(served, out) || insideTree(out, served)) {
    throw new Error(`publish artifact output '${out}' must not be inside the served tree '${served}' (or contain it) — the tree is read-only`);
  }

  const files = await listFiles(served);
  const redirects = await readRedirects(served);
  const { entries, failures } = planArtifact({ files, redirects });

  const sizes = new Map();
  for (const file of files) sizes.set(file, (await stat(path.join(served, file))).size);
  const bytes = artifactBytes(entries, (from) => {
    const size = sizes.get(from);
    if (size === undefined) throw new Error(`planned copy '${from}' is not in the served tree`);
    return size;
  });
  failures.push(...budgetFailures(bytes, cap));
  if (failures.length > 0) throw new ArtifactRefusedError(failures);

  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  for (const entry of entries) {
    const dest = path.join(out, entry.path);
    await mkdir(path.dirname(dest), { recursive: true });
    if ('copy' in entry) await copyFile(path.join(served, entry.copy), dest);
    else await writeFile(dest, entry.body, 'utf8');
  }
  return { files: entries.length, bytes };
}

// ---- CLI ----------------------------------------------------------------------

async function main() {
  const arg = makeArg(process.argv.slice(2));
  const servedDir = path.resolve(ROOT, arg('--served') ?? 'served');
  const outDir = path.resolve(ROOT, arg('--out') ?? '.tmp/publish');
  try {
    const result = await materialize({ servedDir, outDir });
    console.log(`✓ publish artifact: ${result.files} files, ${result.bytes} bytes (cap ${ARTIFACT_BYTE_CAP})`);
    console.log(`  ${path.relative(ROOT, outDir)}/ ← ${path.relative(ROOT, servedDir)}/`);
  } catch (err) {
    if (err instanceof ArtifactRefusedError) {
      console.error(`✗ ${err.message}`);
      process.exitCode = 1;
      return;
    }
    throw err;
  }
}

if (invokedDirectly(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}
