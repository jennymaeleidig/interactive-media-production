/**
 * The shared player's own roster layer, and the js source the roster gives it:
 * it is a `lottie-*` layer like the six, but it has no animations of its own, so
 * it is named before them and excluded from them.
 */
const PLAYER_LAYER = 'lottie-player';
const PLAYER_SOURCE = LAYERS.find((layer) => layer.name === PLAYER_LAYER)?.parts.find((part) => part.kind === 'js')?.source;
if (!PLAYER_SOURCE) throw new Error(`the roster declares no ${PLAYER_LAYER} js source`);

/**
 * The heroes to build, read off the roster: every `lottie-<name>` layer, in the
 * order the roster ships them, joined to its animations. Fails loudly when a
 * declared hero has no animations (the mount cannot choose a container without a
 * stamp) or a vendored one names no declared hero (a leftover), so the two cannot
 * drift apart.
 * @type {{ name: string, route: string, source: string, animations: { json: string, stamp: string }[] }[]}
 */
const HEROES = LAYERS.filter((layer) => layer.name.startsWith('lottie-') && layer.name !== PLAYER_LAYER).map((layer) => {
  const name = layer.name.slice('lottie-'.length);
  const animations = ANIMATIONS[name];
  if (!animations) throw new Error(`${layer.name}: the roster declares it, but no animations are recorded for '${name}'`);
  const [route] = layer.pages ?? [];
  if (!route) throw new Error(`${layer.name}: the roster scopes it to no page`);
  const source = layer.parts.find((part) => part.kind === 'js')?.source;
  if (!source) throw new Error(`${layer.name}: the roster declares no js source`);
  return { name, route, source, animations };
});
for (const name of Object.keys(ANIMATIONS)) {
  if (!LAYERS.some((layer) => layer.name === `lottie-${name}`)) {
    throw new Error(`animations are recorded for '${name}', but the roster declares no lottie-${name} layer`);
  }
}

/**
 * One exact transform on the vendored player: find the snippet, insist it
 * appears the expected number of times, replace it. A drift in the vendored
 * bytes fails loudly rather than shipping a player with a live network path.
 * @type {{ id: string, find: string, replace: string, count: number, why: string }[]}
 */
const NEUTERS = [
  {
    id: 'asset-loader',
    find: 'new XMLHttpRequest',
    replace: '(function(){throw new Error("lottie: data-src loading is disabled in The Recreation")})()',
    count: 1,
    why: 'the data-src fetch path, never taken because every layer passes animationData',
  },
  {
    id: 'expression-globals',
    find: 'window=null,document=null,XMLHttpRequest=null,fetch=null,frames=null,',
    replace: 'window=null,document=null,frames=null,',
    count: 1,
    why: 'ExpressionManager shadow bindings — the two network names can only be dropped, not renamed',
  },
  {
    id: 'expression-keepalive',
    find: '[window,document,XMLHttpRequest,fetch,frames,',
    replace: '[window,document,frames,',
    count: 1,
    why: 'the same two names in __preventDeadCodeRemoval',
  },
];

/** The player's provenance: the vendored build, and exactly what was changed in it. */
const PLAYER_CITATION = `// Citation: Airbnb — lottie-web (v5.13.0) [MIT]
// Source: https://unpkg.com/lottie-web@5.13.0/build/player/lottie.min.js
// Accessed: 2026-09-14
// Vendored unmodified at pipeline/vendor/lottie.min.js; see pipeline/vendor/LOTTIE-CITATION.md.
// Modified for this repository by pipeline/build-lottie-layers.mjs on 2026-09-14 — two
// network primitives removed so the embedded copy satisfies isInertSource.`;

/** The data runtimes' provenance: their JSON is the site's own captured asset, and the player is elsewhere. */
const DATA_CITATION = `// Citation: the animation data inlined here is Flock Safety's own asset, captured from
// cdn.prod.website-files.com and vendored unmodified at pipeline/lottie/*.json. The player
// is not inlined: it ships once as pipeline/lottie/player.runtime.js, which the roster
// loads on this page first.`;

/**
 * Count non-overlapping occurrences of `needle` in `haystack`.
 * @param {string} haystack
 * @param {string} needle
 * @returns {number}
 */
function occurrences(haystack, needle) {
  let count = 0;
  let from = 0;
  for (;;) {
    const at = haystack.indexOf(needle, from);
    if (at === -1) return count;
    count++;
    from = at + needle.length;
  }
}

/**
 * The neutered player: every transform applied with its count proven.
 * @param {string} source
 * @returns {string}
 */
function neuter(source) {
  let out = source;
  for (const step of NEUTERS) {
    const found = occurrences(out, step.find);
    if (found !== step.count) {
      throw new Error(`neuter '${step.id}': expected ${step.count} occurrence(s) of ${JSON.stringify(step.find)}, found ${found} — the vendored player drifted`);
    }
    out = out.split(step.find).join(step.replace);
  }
  if (isInertSource(out) !== true) throw new Error('neuter: the transformed player is not inert');
  return out;
}

/**
 * Every Lottie expression string in one animation: the `x` property wherever a
 * property object carries it. Returns `{ total, banned }` — `banned` entries
 * name the primitive and the expression so the failure is actionable.
 * @param {unknown} value
 * @returns {{ total: number, banned: { expr: string, primitive: string }[] }}
 */
function scanExpressions(value) {
  const expressions = [];
  /** @param {unknown} node */
  const walk = (node) => {
    if (Array.isArray(node)) {
      for (const item of node) walk(item);
      return;
    }
    if (node && typeof node === 'object') {
      for (const [key, child] of Object.entries(node)) {
        if (key === 'x' && typeof child === 'string') expressions.push(child);
        walk(child);
      }
    }
  };
  walk(value);
  const banned = [];
  for (const expr of expressions) {
    const match = NETWORK_PRIMITIVES.exec(expr);
    // the shared regex carries no /g flag, so lastIndex never moves
    if (match) banned.push({ expr, primitive: match[0] });
    NETWORK_PRIMITIVES.lastIndex = 0;
  }
  return { total: expressions.length, banned };
}

/**
 * The mount and play policy, one per page. Each animation's `stamp` selects its
 * container by the captured `data-src` it starts with; a hero with one animation
 * and one container takes the only one. The reduced-motion query is read once for
 * the page, and every animation it silences jumps to its own final frame.
 *
 * It needs the shared player's `window.lottie`, and returns quietly without it —
 * so a page whose player tag is missing renders nothing rather than throwing.
 * ES5-safe, DOM-only.
 * @returns {string}
 */
const MOUNT = `;(function () {
  var ANIMATIONS = __ANIMATIONS__;
  function initiate() {
    if (!window.lottie) return;
    var nodes = document.querySelectorAll('[data-animation-type=lottie]');
    var reduced = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    for (var a = 0; a < ANIMATIONS.length; a++) {
      var DATA = ANIMATIONS[a].data;
      var STAMP = ANIMATIONS[a].stamp;
      var container = null;
      for (var i = 0; i < nodes.length; i++) {
        var src = nodes[i].getAttribute('data-src') || '';
        if (src.indexOf(STAMP) !== -1) { container = nodes[i]; break; }
      }
      if (!container && nodes.length === 1 && ANIMATIONS.length === 1) container = nodes[0];
      if (!container) continue;
      container.removeAttribute('data-src');
      var anim = window.lottie.loadAnimation({
        container: container,
        renderer: 'svg',
        loop: container.getAttribute('data-loop') !== '0',
        autoplay: false,
        animationData: DATA
      });
      if (reduced) {
        anim.goToAndStop((DATA.op || 0) - (DATA.ip || 0) - 1, true);
      } else if (!('IntersectionObserver' in window)) {
        anim.play();
      } else {
        (function (animation, target) {
          var observer = new IntersectionObserver(function (entries) {
            for (var j = 0; j < entries.length; j++) {
              if (entries[j].isIntersecting) { animation.play(); observer.disconnect(); return; }
            }
          });
          observer.observe(target);
        })(anim, container);
      }
    }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initiate, false);
  else initiate();
})();
`;

/**
 * One vendored animation as the object literal the runtime inlines: its stamp and
 * its JSON, verbatim. A `</script` anywhere in it would end the tag early, so it
 * is refused rather than escaped — the vendored bytes stay the vendored bytes.
 * @param {{ json: string, stamp: string }} animation
 * @returns {string}
 */
function inlineAnimation(animation) {
  const raw = readFileSync(path.join(LOTTIE_DIR, animation.json), 'utf8');
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(`${animation.json}: not valid JSON — ${err instanceof Error ? err.message : err}`);
  }
  const { total, banned } = scanExpressions(parsed);
  if (banned.length > 0) {
    const first = banned[0];
    throw new Error(`${animation.json}: expression names ${first.primitive}: ${JSON.stringify(first.expr)} — the ExpressionManager neuter cannot ship`);
  }
  const body = raw.endsWith('\n') ? raw.slice(0, -1) : raw;
  if (/[\u2028\u2029]/.test(body)) throw new Error(`${animation.json}: contains a raw line separator that is not ES5-safe`);
  if (body.includes('</script') || body.includes('</style')) {
    throw new Error(`${animation.json}: contains a tag-closing sequence that would end the inlining tag early`);
  }
  return { text: `{stamp:${JSON.stringify(animation.stamp)},data:${body}}`, expressions: total };
}

function main() {
  const vendor = readFileSync(VENDOR, 'utf8');
  const player = neuter(vendor);
  console.log(`vendor: pipeline/vendor/lottie.min.js (${statSync(VENDOR).size} B) → neutered ${player.length} chars, inert=${isInertSource(player)}`);

  // the player, once, for the pages the roster scopes it to
  const playerRuntime = `${PLAYER_CITATION}\n${player}\n`;
  if (isInertSource(playerRuntime) !== true) throw new Error(`${PLAYER_LAYER} is not inert — refusing to write`);
  writeFileSync(path.join(ROOT, PLAYER_SOURCE), playerRuntime, 'utf8');
  console.log(`  ${PLAYER_LAYER.padEnd(24)} ${String(playerRuntime.length).padStart(9)} chars  sha256_16=${hash16(playerRuntime)}  → ${PLAYER_SOURCE}`);

  for (const hero of HEROES) {
    let expressions = 0;
    const inlined = hero.animations.map((animation) => {
      const part = inlineAnimation(animation);
      expressions += part.expressions;
      return part.text;
    });
    // the substitute must be a function: the data carries `$` sequences that a
    // string replacement would read as capture references
    const runtime = `${DATA_CITATION}\n${MOUNT.replace('__ANIMATIONS__', () => `[${inlined.join(',')}]`)}`;
    if (isInertSource(runtime) !== true) throw new Error(`${hero.name}.runtime.js is not inert — refusing to write`);
    writeFileSync(path.join(ROOT, hero.source), runtime, 'utf8');
    console.log(
      `  ${hero.name.padEnd(24)} anims=${String(hero.animations.length).padStart(2)} exprs=${String(expressions).padStart(2)}  ${String(runtime.length).padStart(9)} chars  sha256_16=${hash16(runtime)}  → ${hero.source}  (${hero.route})`,
    );
  }
}

main();
