// Build the Chat mimic's shipped runtime (`pipeline/chat-runtime.js`).
//
// Two generated, committed artifacts come out of here, and both are generated
// for the same reason: the browser cannot compile Yarn and cannot resolve a
// module graph, so neither step can happen on the served page.
//
//   1. `pipeline/chat-program.json` — `dialogue/flock.yarn` compiled once, at
//      build time, with the Node loader (`yarnspinner-typescript/node`). Keys
//      are sorted recursively so the bytes are a function of the source alone.
//   2. `pipeline/chat-runtime.js` — `pipeline/chat-engine.mjs` bundled by
//      esbuild into one IIFE (the program inlined, the dialogue runtime's
//      browser build tree-shaken), immediately followed by
//      `pipeline/chat-widget.js` verbatim. One asset is what the tree's
//      `chat/js` member carries, so the widget and its engine can never ship
//      out of step.
//
// Run it by hand after editing either source; `npm run check:layers` then fails
// until the tree ships the new bytes (see `pipeline/publish-layers.mjs`).
//
// SPDX-License-Identifier: CC0-1.0
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { loadYarnProject } from 'yarnspinner-typescript/node';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PROJECT_FILE = path.join(ROOT, 'dialogue', 'flock.yarnproject');
const PROGRAM_FILE = path.join(ROOT, 'pipeline', 'chat-program.json');
const ENGINE_FILE = path.join(ROOT, 'pipeline', 'chat-engine.mjs');
const WIDGET_FILE = path.join(ROOT, 'pipeline', 'chat-widget.js');
const RUNTIME_FILE = path.join(ROOT, 'pipeline', 'chat-runtime.js');

const HEADER = [
  '// generated by pipeline/build-chat-runtime.mjs — edit the sources',
  '// sources: pipeline/chat-engine.mjs + pipeline/chat-widget.js + pipeline/chat-program.json',
  '',
  '',
].join('\n');

/**
 * Sort every object's keys recursively so the compiled program's bytes depend
 * on the source, not on the compiler's insertion order. Array order is
 * semantic (instructions, lines) and is preserved.
 * @param {unknown} value
 * @returns {unknown}
 */
function stableKeys(value) {
  if (Array.isArray(value)) return value.map(stableKeys);
  if (value && typeof value === 'object') {
    /** @type {Record<string, unknown>} */
    const sorted = {};
    for (const key of Object.keys(value).sort()) {
      sorted[key] = stableKeys(/** @type {Record<string, unknown>} */ (value)[key]);
    }
    return sorted;
  }
  return value;
}

/** Compile `dialogue/flock.yarn` and write the deterministic program JSON. */
function writeProgram() {
  const project = loadYarnProject(PROJECT_FILE);
  if (!project.program) {
    const problems = project.diagnostics.map((diagnostic) => `${diagnostic.code}: ${diagnostic.message}`).join('\n');
    throw new Error(`dialogue/flock.yarn failed to compile:\n${problems}`);
  }
  writeFileSync(PROGRAM_FILE, `${JSON.stringify(stableKeys(project.program), null, 2)}\n`, 'utf8');
  return readFileSync(PROGRAM_FILE, 'utf8').length;
}

/** Bundle the engine and concatenate the widget; returns the asset's size. */
async function writeRuntime() {
  const result = await build({
    entryPoints: [ENGINE_FILE],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2017',
    legalComments: 'none',
    write: false,
  });
  const engine = result.outputFiles[0].text;
  const widget = readFileSync(WIDGET_FILE, 'utf8');
  const runtime = HEADER + engine + '\n' + widget;
  writeFileSync(RUNTIME_FILE, runtime, 'utf8');
  return runtime.length;
}

const programBytes = writeProgram();
const runtimeBytes = await writeRuntime();
console.log(`chat-program.json: ${programBytes} bytes`);
console.log(`chat-runtime.js:   ${runtimeBytes} bytes`);
